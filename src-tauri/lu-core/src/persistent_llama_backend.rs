//! Persistent Lu-owned GGUF engine based on an explicitly pinned llama.cpp
//! \`llama-server\` binary. One supervised child retains weights across calls.
//!
//! The authenticated 127.0.0.1 HTTP interface is an implementation boundary
//! to upstream llama.cpp, NOT an internal Lu/MCP tool protocol. Lu commands,
//! policies and model/tool events remain Protobuf-native in the host.
//! Initial implementation: CPU-only, text completion, one generation at a time.
//! A signed, immutable engine package and model-file identity are required
//! before a production release.
use crate::inference_host::{
    Cancellation, EngineError, GenerationRequest, InferenceBackend, TokenChunk,
};
use crate::model_admission::AdmittedModel;
use serde_json::json;
use sha2::{Digest, Sha256};
use std::{
    fs::{self, File, OpenOptions},
    io::{self, BufRead, BufReader, Read, Write},
    net::{Ipv4Addr, SocketAddr, TcpListener, TcpStream},
    num::NonZeroUsize,
    path::{Path, PathBuf},
    process::{Child, Command, Stdio},
    thread,
    time::{Duration, Instant},
};

const MAX_RESPONSE_BYTES: usize = 16 * 1024 * 1024;
const MAX_HEADERS_BYTES: usize = 16 * 1024;
const MAX_EVENT_BYTES: usize = 64 * 1024;

/// Values originate from a host-controlled engine manifest and configuration;
/// none may be taken from model-generated text or tool arguments.
pub struct PersistentEngineConfig {
    pub executable: PathBuf,
    pub expected_sha256: [u8; 32],
    pub threads: NonZeroUsize,
    pub context_tokens: u32,
    pub startup_timeout: Duration,
    pub request_timeout: Duration,
    pub api_key: String,
}

pub struct PersistentLlamaBackend {
    config: PersistentEngineConfig,
    canonical_executable: PathBuf,
    pinned_model_file: Option<File>,
    process: Option<Child>,
    port: Option<u16>,
}

fn verify_engine(path: &Path, expected: &[u8; 32]) -> Result<PathBuf, String> {
    if expected.iter().all(|byte| *byte == 0) {
        return Err("engine must have a trusted nonzero SHA-256 digest".into());
    }
    if !fs::symlink_metadata(path)
        .map_err(|e| e.to_string())?
        .file_type()
        .is_file()
    {
        return Err("engine is not an ordinary file".into());
    }
    let canonical = path.canonicalize().map_err(|e| e.to_string())?;
    let mut file = File::open(&canonical).map_err(|e| e.to_string())?;
    let mut hasher = Sha256::new();
    let mut buffer = [0u8; 65536];
    loop {
        let count = file.read(&mut buffer).map_err(|e| e.to_string())?;
        if count == 0 {
            break;
        }
        hasher.update(&buffer[..count]);
    }
    if hasher.finalize().as_slice() != expected {
        return Err("engine SHA-256 mismatch".into());
    }
    Ok(canonical)
}

/// Sufficient entropy must be generated by the trusted host. No API key is
/// written into repo config. For now the host must supply 64 hex characters.
fn valid_api_key(value: &str) -> bool {
    value.len() == 64 && value.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Lu composes ChatML prompts before this HTTP boundary. Limit generation to
/// the current assistant span; role delimiters must not become another turn.
fn completion_request_body(prompt: &str, max_new_tokens: u32) -> String {
    json!({
        "prompt": prompt,
        "n_predict": max_new_tokens,
        "temperature": 0.0,
        "stream": true,
        "cache_prompt": true,
        "stop": ["<|im_end|>", "<|im_start|>"],
    })
    .to_string()
}

impl PersistentLlamaBackend {
    pub fn new(config: PersistentEngineConfig) -> Result<Self, String> {
        if !valid_api_key(&config.api_key) {
            return Err("engine requires a host-generated 256-bit hexadecimal API key".into());
        }
        if config.context_tokens < 256
            || config.context_tokens > 1_048_576
            || config.threads.get() > 256
            || config.startup_timeout.is_zero()
            || config.startup_timeout > Duration::from_secs(600)
            || config.request_timeout.is_zero()
            || config.request_timeout > Duration::from_secs(3600)
        {
            return Err("invalid persistent inference resource limits".into());
        }
        let canonical_executable = verify_engine(&config.executable, &config.expected_sha256)?;
        Ok(Self {
            config,
            canonical_executable,
            pinned_model_file: None,
            process: None,
            port: None,
        })
    }
    pub fn pid(&self) -> Option<u32> {
        self.process.as_ref().map(Child::id)
    }
    pub fn is_running(&mut self) -> bool {
        self.process
            .as_mut()
            .is_some_and(|p| matches!(p.try_wait(), Ok(None)))
    }
    fn active_port(&mut self) -> Result<u16, String> {
        if !self.is_running() {
            return Err("persistent llama.cpp engine is not running".into());
        }
        self.port
            .ok_or("persistent inference endpoint missing".into())
    }
    fn wait_ready(&mut self, deadline: Instant, port: u16) -> Result<(), String> {
        loop {
            if !self.is_running() {
                return Err("persistent llama.cpp engine exited during model loading".into());
            }
            if Instant::now() >= deadline {
                return Err("persistent GGUF model load timed out".into());
            }
            let address = SocketAddr::from((Ipv4Addr::LOCALHOST, port));
            if let Ok(mut socket) = TcpStream::connect_timeout(&address, Duration::from_millis(150))
            {
                let _ = socket.set_read_timeout(Some(Duration::from_millis(250)));
                let _ = socket.set_write_timeout(Some(Duration::from_millis(250)));
                let request = format!(
                    "GET /health HTTP/1.1\r\nHost: 127.0.0.1\r\nAuthorization: Bearer {}\r\nConnection: close\r\n\r\n",
                    self.config.api_key
                );
                if socket.write_all(request.as_bytes()).is_ok() {
                    let mut reader = BufReader::new(socket);
                    let mut status = String::new();
                    if reader.read_line(&mut status).is_ok() && status.starts_with("HTTP/1.1 200 ")
                    {
                        return Ok(());
                    }
                }
            }
            thread::sleep(Duration::from_millis(100));
        }
    }
}
impl InferenceBackend for PersistentLlamaBackend {
    fn process_id(&self) -> Option<u32> {
        self.pid()
    }
    fn load(&mut self, admitted: &AdmittedModel) -> Result<(), String> {
        if self.process.is_some() {
            return Err("persistent engine already owns a model".into());
        }
        admitted.recheck().map_err(|e| format!("{e:?}"))?;
        // Windows share-read mode rejects normal replacement of the model file.
        // A production loader must additionally pin the complete engine package
        // and link its process to a Windows kill-on-close Job Object.
        let mut open = OpenOptions::new();
        open.read(true);
        #[cfg(windows)]
        {
            use std::os::windows::fs::OpenOptionsExt;
            open.share_mode(0x00000001); // FILE_SHARE_READ
        }
        let file = open.open(admitted.path()).map_err(|e| e.to_string())?;
        if file.metadata().map_err(|e| e.to_string())?.len() != admitted.header().file_bytes {
            return Err("GGUF size changed at engine start".into());
        }
        admitted.recheck().map_err(|e| format!("{e:?}"))?;
        verify_engine(&self.canonical_executable, &self.config.expected_sha256)?;

        // Host picks an ephemeral loopback port, never accepting an endpoint
        // supplied by the model. A bind race is handled by failing closed if
        // llama-server does not start; it never falls back to a foreign server.
        let listener = TcpListener::bind((Ipv4Addr::LOCALHOST, 0)).map_err(|e| e.to_string())?;
        let port = listener.local_addr().map_err(|e| e.to_string())?.port();
        drop(listener);

        let mut command = Command::new(&self.canonical_executable);
        command
            .arg("--model")
            .arg(admitted.path())
            .arg("--host")
            .arg("127.0.0.1")
            .arg("--port")
            .arg(port.to_string())
            .arg("--api-key")
            .arg(&self.config.api_key)
            .arg("--threads")
            .arg(self.config.threads.get().to_string())
            .arg("--ctx-size")
            .arg(self.config.context_tokens.to_string())
            .arg("--parallel")
            .arg("1")
            .arg("--n-gpu-layers")
            .arg("0")
            .arg("--no-warmup")
            .current_dir(
                self.canonical_executable
                    .parent()
                    .ok_or("invalid engine location")?,
            )
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null());
        for (name, _) in std::env::vars_os() {
            let key = name.to_string_lossy();
            if key.starts_with("LLAMA_ARG_") || key == "LLAMA_API_KEY" {
                command.env_remove(name);
            }
        }
        #[cfg(windows)]
        {
            use std::os::windows::process::CommandExt;
            command.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
        }
        let child = command.spawn().map_err(|e| e.to_string())?;
        self.process = Some(child);
        self.pinned_model_file = Some(file);
        self.port = Some(port);
        let deadline = Instant::now() + self.config.startup_timeout;
        if let Err(error) = self.wait_ready(deadline, port) {
            self.unload();
            return Err(error);
        }
        Ok(())
    }
    fn unload(&mut self) {
        if let Some(mut child) = self.process.take() {
            let _ = child.kill();
            let _ = child.wait();
        }
        self.port = None;
        self.pinned_model_file = None;
    }
    fn generate(
        &mut self,
        request: &GenerationRequest,
        cancel: &Cancellation,
        emit: &mut dyn FnMut(TokenChunk) -> Result<(), EngineError>,
    ) -> Result<(), String> {
        if cancel.is_cancelled() {
            return Err("generation cancelled".into());
        }
        let port = self.active_port()?;
        let deadline = Instant::now() + self.config.request_timeout;
        let address = SocketAddr::from((Ipv4Addr::LOCALHOST, port));
        let mut socket = TcpStream::connect_timeout(&address, Duration::from_secs(2))
            .map_err(|e| e.to_string())?;
        socket
            .set_read_timeout(Some(Duration::from_millis(250)))
            .map_err(|e| e.to_string())?;
        socket
            .set_write_timeout(Some(Duration::from_secs(2)))
            .map_err(|e| e.to_string())?;
        let body = completion_request_body(&request.prompt, request.max_new_tokens);
        let headers = format!(
            "POST /completion HTTP/1.1\r\nHost: 127.0.0.1\r\nAuthorization: Bearer {}\r\nContent-Type: application/json\r\nAccept: text/event-stream\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            self.config.api_key, body.len()
        );
        socket
            .write_all(headers.as_bytes())
            .map_err(|e| e.to_string())?;
        socket
            .write_all(body.as_bytes())
            .map_err(|e| e.to_string())?;
        let mut reader = BufReader::new(socket);
        let status = read_line_bounded(&mut reader, deadline, cancel, MAX_HEADERS_BYTES)?;
        if !status.starts_with("HTTP/1.1 200 ") && !status.starts_with("HTTP/1.0 200 ") {
            return Err(format!(
                "inference endpoint rejected request: {}",
                status.trim()
            ));
        }
        let mut header_total = status.len();
        let mut chunked = false;
        loop {
            let line = read_line_bounded(&mut reader, deadline, cancel, MAX_HEADERS_BYTES)?;
            header_total += line.len();
            if header_total > MAX_HEADERS_BYTES {
                return Err("oversized inference response headers".into());
            }
            if line == "\r\n" || line == "\n" {
                break;
            }
            if line.to_ascii_lowercase().starts_with("transfer-encoding:")
                && line.to_ascii_lowercase().contains("chunked")
            {
                chunked = true;
            }
        }
        if !chunked {
            return Err("engine did not provide a bounded chunked event stream".into());
        }
        let mut events = Vec::new();
        let mut total = 0usize;
        let mut index = 0u32;
        let mut stopped = false;
        let mut event_count = 0u32;
        let mut content_fields = 0u32;
        let mut predicted_tokens = None;
        let mut stop_type = String::new();
        while !stopped {
            let count_line = read_line_bounded(&mut reader, deadline, cancel, 128)?;
            let length_hex = count_line.trim().split(';').next().unwrap_or("");
            let length = usize::from_str_radix(length_hex, 16)
                .map_err(|_| "invalid chunked inference framing")?;
            if length == 0 {
                break;
            }
            if length > MAX_EVENT_BYTES || total.saturating_add(length) > MAX_RESPONSE_BYTES {
                return Err("inference response exceeded byte limit".into());
            }
            let mut chunk = vec![0u8; length];
            read_exact_until(&mut reader, &mut chunk, deadline, cancel)?;
            let mut end = [0u8; 2];
            read_exact_until(&mut reader, &mut end, deadline, cancel)?;
            if end != *b"\r\n" {
                return Err("invalid inference chunk terminator".into());
            }
            total += length;
            events.extend_from_slice(&chunk);
            if events.len() > MAX_EVENT_BYTES {
                return Err("oversized inference event".into());
            }
            while let Some(data) = take_sse_frame(&mut events) {
                let payload =
                    std::str::from_utf8(&data).map_err(|_| "invalid UTF-8 in inference event")?;
                for line in payload
                    .lines()
                    .filter_map(|line| line.strip_prefix("data: "))
                {
                    if line == "[DONE]" {
                        stopped = true;
                        break;
                    }
                    let event: serde_json::Value = serde_json::from_str(line)
                        .map_err(|e| format!("malformed inference event: {e}"))?;
                    event_count = event_count.saturating_add(1);
                    if event.get("content").is_some() {
                        content_fields = content_fields.saturating_add(1);
                    }
                    if let Some(n) = event.get("tokens_predicted").and_then(|v| v.as_u64()) {
                        predicted_tokens = Some(n);
                    }
                    if let Some(kind) = event.get("stop_type").and_then(|v| v.as_str()) {
                        stop_type = kind.to_owned();
                    }
                    if let Some(text) = event.get("content").and_then(|x| x.as_str()) {
                        if !text.is_empty() {
                            emit(TokenChunk {
                                text: text.to_owned(),
                                index,
                            })
                            .map_err(|e| format!("inference output callback failed: {e:?}"))?;
                            index = index.saturating_add(1);
                        }
                    }
                    if event.get("stop").and_then(|x| x.as_bool()) == Some(true) {
                        stopped = true;
                        break;
                    }
                }
            }
        }
        if cancel.is_cancelled() {
            return Err("generation cancelled".into());
        }
        if index == 0 {
            return Err(format!("persistent engine produced no text: events={event_count}, content_fields={content_fields}, predicted_tokens={predicted_tokens:?}, stop_type={stop_type}"));
        }
        Ok(())
    }
}
impl Drop for PersistentLlamaBackend {
    fn drop(&mut self) {
        self.unload();
    }
}
/// SSE event separators are independent from HTTP chunk boundaries.
/// Return exactly one fully buffered frame, leaving incomplete data untouched.
fn take_sse_frame(buffer: &mut Vec<u8>) -> Option<Vec<u8>> {
    let lf = buffer
        .windows(2)
        .position(|part| part == b"\n\n")
        .map(|p| (p, 2));
    let crlf = buffer
        .windows(4)
        .position(|part| part == b"\r\n\r\n")
        .map(|p| (p, 4));
    let (at, len) = match (lf, crlf) {
        (Some(a), Some(b)) => {
            if a.0 < b.0 {
                a
            } else {
                b
            }
        }
        (Some(a), None) => a,
        (None, Some(b)) => b,
        (None, None) => return None,
    };
    Some(buffer.drain(..at + len).collect())
}

fn read_line_bounded(
    reader: &mut BufReader<TcpStream>,
    deadline: Instant,
    cancel: &Cancellation,
    max: usize,
) -> Result<String, String> {
    let mut bytes = Vec::new();
    loop {
        if cancel.is_cancelled() {
            return Err("generation cancelled".into());
        }
        if Instant::now() >= deadline {
            return Err("generation deadline exceeded".into());
        }
        let mut byte = [0u8; 1];
        match reader.read(&mut byte) {
            Ok(0) => return Err("inference endpoint closed connection".into()),
            Ok(_) => {
                bytes.push(byte[0]);
                if byte[0] == b'\n' {
                    break;
                }
            }
            Err(e)
                if e.kind() == io::ErrorKind::WouldBlock || e.kind() == io::ErrorKind::TimedOut =>
            {
                continue
            }
            Err(e) => return Err(e.to_string()),
        }
        if bytes.len() > max {
            return Err("inference line exceeds protocol limit".into());
        }
    }
    String::from_utf8(bytes).map_err(|_| "inference protocol line is not UTF-8".into())
}
fn read_exact_until(
    reader: &mut BufReader<TcpStream>,
    buf: &mut [u8],
    deadline: Instant,
    cancel: &Cancellation,
) -> Result<(), String> {
    let mut position = 0;
    while position < buf.len() {
        if cancel.is_cancelled() {
            return Err("generation cancelled".into());
        }
        if Instant::now() >= deadline {
            return Err("generation deadline exceeded".into());
        }
        match reader.read(&mut buf[position..]) {
            Ok(0) => return Err("truncated inference response".into()),
            Ok(n) => position += n,
            Err(e)
                if e.kind() == io::ErrorKind::WouldBlock || e.kind() == io::ErrorKind::TimedOut => {
            }
            Err(e) => return Err(e.to_string()),
        }
    }
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn api_key_requires_full_host_entropy() {
        assert!(!valid_api_key("1234"));
        assert!(valid_api_key(&"0a".repeat(32)));
    }
    #[test]
    fn sse_frames_survive_arbitrary_http_chunk_splits() {
        let mut buffer = Vec::new();
        buffer.extend_from_slice(b"data: {\"content\":\"Hello\",\"stop\":false}\n");
        assert!(take_sse_frame(&mut buffer).is_none());
        buffer.extend_from_slice(b"\ndata: {\"content\":\" world\",\"stop\":false}\r\n");
        let first = take_sse_frame(&mut buffer).unwrap();
        assert!(String::from_utf8(first).unwrap().contains("Hello"));
        assert!(take_sse_frame(&mut buffer).is_none());
        buffer.extend_from_slice(b"\r\n");
        let second = take_sse_frame(&mut buffer).unwrap();
        assert!(String::from_utf8(second).unwrap().contains(" world"));
        assert!(buffer.is_empty());
    }

    #[test]
    fn refuses_unsigned_engine_identity() {
        assert!(verify_engine(Path::new("missing"), &[0u8; 32]).is_err());
    }
}
