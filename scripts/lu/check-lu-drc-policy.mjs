// Offline, dependency-free DESIGN CONTRACT validation. NOT runtime enforcement.
import assert from 'node:assert/strict'
import fs from 'node:fs'
export function validateLuDrcPolicy(p) {
  assert.equal(p.schema,'lu-drc-policy-v1')
  assert.equal(p.decision_id,'ADR-LU-DRC-001')
  assert.equal(p.architectural_status,'accepted_design')
  assert.equal(p.implementation_status,'not_implemented')
  assert.equal(p.offline_first,true)
  assert.equal(p.main.can_mutate_installed_release,false)
  assert.equal(p.dev.headless_default,true)
  assert.equal(p.dev.can_mutate_stable_files,false)
  assert.equal(p.dev.can_promote_release,false)
  assert.equal(p.dev.can_write_guardian_refs,false)
  assert.equal(p.inference.single_resident_model_default,true)
  assert.equal(p.inference.dev_auto_load_duplicate_model,false)
  assert.equal(p.git.branch_from_any_retained_verified_stable_commit,true)
  assert.equal(p.git.protected_refs_unwritable_by_dev,true)
  assert.equal(p.git.github_required_for_local_operations,false)
  assert.equal(p.git.staging_merge_equals_deployment,false)
  assert.equal(p.release.installed_binaries_guardian_only,true)
  assert.equal(p.release.human_approval_required_for_core_promotion,true)
  assert.equal(p.release.consent_bound_to_exact_artifact_digest,true)
  assert.equal(p.release.dev_self_certification_allowed,false)
  assert.equal(p.release.independent_verified_evidence_required,true)
  assert.equal(p.release.staging_merge_requires_post_merge_tests,true)
  assert.equal(p.release.dual_slot_install_required,true)
  assert.equal(p.release.previous_known_good_retained,true)
  assert.equal(p.release.automatic_rollback_on_failed_health,true)
  assert.equal(p.release.no_live_core_binary_hotswap,true)
  assert.equal(p.rollback.branchable_source,'any_retained_verified_stable_source')
  assert.equal(p.rollback.runnable_target,'retained_verified_binary_and_compatible_state')
  assert.equal(p.rollback.git_tag_alone_sufficient,false)
  assert.equal(p.rollback.forbid_silent_irreversible_schema_downgrade,true)
  assert.equal(p.rollback.preserve_newer_conversations,true)
  assert.equal(p.rollback.guardian_works_without_main_or_model,true)
  assert.ok(Array.isArray(p.gates))
  assert.equal(p.gates.length,13)
  const ids=p.gates.map(g=>g.id)
  assert.deepEqual(ids,Array.from({length:13},(_,i)=>'DRC-'+String(i).padStart(2,'0')))
  assert.equal(new Set(ids).size,ids.length)
  return true
}
if (process.argv[1]?.endsWith('check-lu-drc-policy.mjs')) {
  const file=new URL('../../docs/lu/lu-drc-policy-v1.json',import.meta.url)
  validateLuDrcPolicy(JSON.parse(fs.readFileSync(file,'utf8')))
  console.log('LU_DRC_DESIGN_POLICY_VALIDATED runtime_enforcement=false gates=13')
}
